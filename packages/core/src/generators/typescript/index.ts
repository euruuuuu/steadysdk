const NOTICE = '// Generated by steadysdk. Do not edit: changes are overwritten on the next run.';
const REGIONS_NOTICE = '// Generated by steadysdk. Edit only inside `// <steadysdk:custom>` regions: the rest is overwritten on the next run.';
const RUNTIME_MODULE = 'generated/runtime.ts';

/** Names the generated code itself defines or relies on; schemas that clash get `types.reservedSuffix`. */
const RESERVED_TYPE_NAMES = [
  // Exported by generated/client.ts and generated/webhooks.ts
  'GeneratedClient', 'ClientOptions', 'AuthCredentials', 'DEFAULT_BASE_URL', 'SECURITY_SCHEMES', 'WebhookPayloads', 'WebhookName',
  // Globals referenced by generated types
  'Array', 'ArrayBuffer', 'BigInt', 'Blob', 'Boolean', 'Date', 'Error', 'File', 'FormData', 'Function', 'Headers',
  'JSON', 'Map', 'Math', 'Number', 'Object', 'Omit', 'Partial', 'Pick', 'Promise', 'Readonly', 'Record', 'RegExp',
  'Request', 'RequestInit', 'Required', 'Response', 'Set', 'String', 'Symbol', 'URL', 'URLSearchParams', 'Uint8Array',
  // Words that cannot name a type
  'any', 'as', 'bigint', 'boolean', 'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'declare',
  'default', 'delete', 'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if',
  'implements', 'import', 'in', 'infer', 'instanceof', 'interface', 'keyof', 'let', 'never', 'new', 'null', 'number',
  'object', 'package', 'private', 'protected', 'public', 'readonly', 'return', 'static', 'string', 'super', 'switch',
  'symbol', 'this', 'throw', 'true', 'try', 'type', 'typeof', 'undefined', 'unique', 'unknown', 'var', 'void', 'while',
  'with', 'yield',
];

export interface TypeScriptGeneratorInput {
  model: ApiModel;
  config: SteadySdkConfig;
  lock?: NameLock | undefined;
  diagnostics: Diagnostics;
  /** Source of generated/runtime.ts (a `templates.runtime` override); defaults to the built-in runtime. */
  runtimeSource?: string | undefined;
}

export interface GeneratorOutput {
  files: GeneratedFile[];
  names: SdkNames;
  lock: NameLock;
}

/** Produces the TypeScript SDK as an in-memory file list; writing is the caller's job. */
export async function generateTypeScript(input: TypeScriptGeneratorInput): Promise<GeneratorOutput> {
  const { model, config, diagnostics } = input;
  const runtimeSource = (input.runtimeSource ?? (await builtinRuntime())).replace(/^\/\/ Generated by steadysdk\..*\n/, '');
  const regions = config.typescript.customRegions;
  const header = fileHeader(config, model);
  const trackers: ImportTracker[] = [];

  const { names, lock } = assignNames({
    model,
    config,
    lock: input.lock,
    reservedTypeNames: [...RESERVED_TYPE_NAMES, ...exportedNames(runtimeSource)],
    reservedMemberNames: ['http'],
    derivedTypes: derivedTypesFor,
    diagnostics,
  });

  const ext = config.typescript.importExtension === 'none' ? '' : config.typescript.importExtension;
  const importPath = (from: string, to: string): string => {
    let relative = path.posix.relative(path.posix.dirname(from), to).replace(/\.ts$/, ext);
    if (!relative.startsWith('.')) relative = `./${relative}`;
    return relative;
  };

  const schemesByKey = new Map(model.securitySchemes.map((scheme) => [scheme.key, scheme]));
  const schemeKeys = new Set(schemesByKey.keys());

  const groupFiles = assignGroupFiles(names);
  const operationsByGroup = new Map<string, Operation[]>();
  for (const op of model.operations) {
    const group = names.operations.get(op.key)!.group;
    operationsByGroup.set(group, [...(operationsByGroup.get(group) ?? []), op]);
  }

  const files: GeneratedFile[] = [
    { path: RUNTIME_MODULE, content: `${header(NOTICE)}\n${runtimeSource}`, ownership: 'generated' },
    { path: 'generated/models.ts', content: modelsFile(model, names, header(regions ? REGIONS_NOTICE : NOTICE), regions), ownership: 'generated' },
  ];

  for (const [groupId, group] of names.groups) {
    const file = groupFiles.get(groupId)!;
    const tag = model.tags.find((candidate) => candidate.name === groupId);
    const imports = new ImportTracker(file, importPath);
    trackers.push(imports);
    imports.type(RUNTIME_MODULE, 'HttpClient');
    imports.type(RUNTIME_MODULE, 'RequestOptions');

    const body = new CodeWriter();
    const ctx = imports.typeContext(names);
    const ops = operationsByGroup.get(groupId) ?? [];
    for (const op of ops) writeOperationTypes(body, op, names.operations.get(op.key)!, ctx);
    body.blank();
    body.doc(tag?.description ? [tag.description] : [`Operations tagged \`${groupId}\`.`]);
    body.block(`export class ${group.className} {`, () => {
      body.line('protected readonly http: HttpClient;');
      body.blank();
      body.block('constructor(http: HttpClient) {', () => body.line('this.http = http;'));
      for (const op of ops) writeOperationMethod(body, op, names.operations.get(op.key)!, ctx, schemeKeys);
      if (regions) body.blank().line(emptyRegion('members').join('\n'));
    });

    const content = assemble(header(regions ? REGIONS_NOTICE : NOTICE), imports, body, regions ? emptyRegion('imports') : []);
    files.push({ path: file, content, ownership: 'generated' });
  }

  const webhooksFile = model.webhooks.length > 0 ? 'generated/webhooks.ts' : undefined;
  if (webhooksFile) {
    const imports = new ImportTracker(webhooksFile, importPath);
    const body = webhooksBody(model, imports.typeContext(names));
    files.push({ path: webhooksFile, content: assemble(header(NOTICE), imports, body, []), ownership: 'generated' });
  }

  const clientImports = new ImportTracker('generated/client.ts', importPath);
  trackers.push(clientImports);
  files.push({
    path: 'generated/client.ts',
    content: clientFile(model, config, names, operationsByGroup.get('') ?? [], groupFiles, schemesByKey, clientImports, header(NOTICE)),
    ownership: 'generated',
  });

  const barrel = new CodeWriter().line(header(NOTICE)).blank();
  for (const file of [RUNTIME_MODULE, 'generated/models.ts', 'generated/client.ts', ...groupFiles.values(), ...(webhooksFile ? [webhooksFile] : [])]) {
    barrel.line(`export * from ${stringLiteral(importPath('generated/index.ts', file))};`);
  }
  files.push({ path: 'generated/index.ts', content: barrel.toString(), ownership: 'generated' });

  checkRuntimeContract(runtimeSource, trackers, input.runtimeSource !== undefined);

  // Scaffolds are yours after the first run, so they get the configured header but not the "Generated" notice.
  const scaffoldHeader = (writer: CodeWriter): CodeWriter => (config.templates.header === undefined ? writer : writer.line(header()).blank());
  files.push(
    {
      path: 'index.ts',
      content: scaffoldHeader(new CodeWriter())
        .line('// Entry point of your SDK. steadysdk created this file once and will not modify it again.')
        .blank()
        .line(`export * from ${stringLiteral(importPath('index.ts', 'generated/index.ts'))};`)
        .line(`export { ${names.client} } from ${stringLiteral(importPath('index.ts', 'client.ts'))};`)
        .toString(),
      ownership: 'scaffold',
    },
    {
      path: 'client.ts',
      content: scaffoldHeader(new CodeWriter())
        .line(`import { GeneratedClient } from ${stringLiteral(importPath('client.ts', 'generated/index.ts'))};`)
        .blank()
        .doc([
          `The client your application uses. steadysdk created this file once and will not modify it again,`,
          'so helpers, defaults and overrides added here survive every regeneration.',
        ])
        .line(`export class ${names.client} extends GeneratedClient {}`)
        .toString(),
      ownership: 'scaffold',
    },
  );

  return { files, names, lock };
}

/** The configured header lines (placeholders filled in), followed by `notice` when given. */
function fileHeader(config: SteadySdkConfig, model: ApiModel): (notice?: string) => string {
  const oneLine = (text: string): string => text.replace(/\s+/g, ' ');
  const lines =
    config.templates.header
      ?.trimEnd()
      .split('\n')
      .map((line) => line.replace(/\{title\}/g, oneLine(model.title)).replace(/\{version\}/g, oneLine(model.version))) ?? [];
  return (notice) => [...lines, ...(notice === undefined ? [] : [notice])].join('\n');
}

/**
 * A runtime override must export every name the generated code imports from it. (Signatures are left to
 * the TypeScript compiler; this catches the common mistake early, with a clear message.)
 */
function checkRuntimeContract(source: string, trackers: readonly ImportTracker[], isOverride: boolean): void {
  if (!isOverride || /^export\s+\*/m.test(source)) return; // `export *` re-exports cannot be checked here
  const exported = new Set(exportedNames(source));
  const missing = [...new Set(trackers.flatMap((tracker) => tracker.namesFrom(RUNTIME_MODULE)))].filter((name) => !exported.has(name)).sort();
  if (missing.length === 0) return;
  throw new SteadySdkError('TEMPLATE_INVALID', 'The runtime template (templates.runtime) is missing exports the generated code imports', {
    details: missing.map((name) => `export ${name}`),
    hint: 'Compare it with the built-in runtime: `steadysdk eject runtime --stdout`.',
  });
}

/** `WebhookPayloads`: webhook name → the body its handler receives. */
function webhooksBody(model: ApiModel, ctx: TypeContext): CodeWriter {
  const body = new CodeWriter();
  const example = model.webhooks[0]!.key;
  body.blank();
  body.doc([
    'Payloads of the webhooks this API sends, by webhook name.',
    `\`WebhookPayloads[${stringLiteral(example)}]\` is the body a \`${example}\` handler receives.`,
  ]);
  body.block('export interface WebhookPayloads {', () => {
    for (const hook of model.webhooks) {
      const docs = [hook.summary, hook.description !== hook.summary ? hook.description : undefined].filter((line) => line !== undefined);
      body.doc([...docs, ...(hook.deprecated ? ['@deprecated'] : [])]);
      body.line(`${propertyKey(hook.key)}: ${bodyType(hook.payload?.content ?? [], ctx) ?? 'undefined'};`);
    }
  });
  body.blank();
  body.doc(['Names of the webhooks this API sends.']);
  body.line('export type WebhookName = keyof WebhookPayloads;');
  return body;
}

function modelsFile(model: ApiModel, names: SdkNames, header: string, regions: boolean): string {
  const writer = new CodeWriter().line(header);
  const ctx: TypeContext = { ref: (key) => names.schemas.get(key) ?? 'unknown' };
  for (const { key, schema } of model.schemas) {
    const name = names.schemas.get(key)!;
    writer.blank();
    writer.doc(schemaDocs(schema, schema.description ?? schema.title));
    if (schema.kind === 'object' && schema.properties.length > 0 && !schema.nullable) {
      writer.block(`export interface ${name} {`, () => writeMembers(writer, schema, ctx));
    } else {
      writer.line(`export type ${name} = ${renderType(schema, ctx)};`);
    }
  }
  if (model.schemas.length === 0) writer.blank().line('export {};');
  // Extra declarations next to the models: type guards, helper types, interface merging.
  if (regions) writer.blank().line(emptyRegion('declarations').join('\n'));
  return writer.toString();
}

function clientFile(
  model: ApiModel,
  config: SteadySdkConfig,
  names: SdkNames,
  rootOperations: Operation[],
  groupFiles: ReadonlyMap<string, string>,
  schemes: ReadonlyMap<string, SecurityScheme>,
  imports: ImportTracker,
  header: string,
): string {
  imports.value(RUNTIME_MODULE, 'HttpClient');
  imports.type(RUNTIME_MODULE, 'ClientConfig');
  imports.type(RUNTIME_MODULE, 'SecuritySchemeDefinition');
  if (rootOperations.length > 0) imports.type(RUNTIME_MODULE, 'RequestOptions');
  for (const [groupId, group] of names.groups) imports.value(groupFiles.get(groupId)!, group.className);

  const body = new CodeWriter();
  const ctx = imports.typeContext(names);
  const baseUrl = config.client.baseUrl ?? model.servers[0]?.url;

  body.blank();
  body.doc(['Base URL from the spec (`servers[0]`), unless overridden by `client.baseUrl` in the steadysdk config.']);
  body.line(`export const DEFAULT_BASE_URL: string | undefined = ${baseUrl === undefined ? 'undefined' : stringLiteral(baseUrl)};`);

  body.blank();
  body.block('export const SECURITY_SCHEMES: Readonly<Record<string, SecuritySchemeDefinition>> = {', () => {
    for (const scheme of schemes.values()) body.line(`${propertyKey(scheme.key)}: ${literal(schemeDefinition(scheme))},`);
  }, '};');

  body.blank();
  body.doc(['Credentials for the API\'s security schemes. Each is optional; provide the ones your calls need.']);
  if (schemes.size === 0) {
    body.line('export type AuthCredentials = Record<string, never>;');
  } else {
    body.block('export type AuthCredentials = {', () => {
      for (const scheme of schemes.values()) {
        const basic = scheme.type === 'http' && scheme.scheme === 'basic';
        imports.type(RUNTIME_MODULE, 'CredentialValue');
        if (basic) imports.type(RUNTIME_MODULE, 'BasicCredentials');
        body.doc([...(scheme.description ? [scheme.description] : []), schemeUsage(scheme)]);
        body.line(`${propertyKey(scheme.key)}?: ${basic ? 'BasicCredentials | CredentialValue' : 'CredentialValue'};`);
      }
    }, '};');
  }

  body.blank();
  body.block("export interface ClientOptions extends Omit<ClientConfig, 'auth'> {", () => {
    body.line('auth?: AuthCredentials | undefined;');
  });

  for (const op of rootOperations) writeOperationTypes(body, op, names.operations.get(op.key)!, ctx);

  body.blank();
  body.doc([
    `Generated client for ${model.title} (API version ${model.version}).`,
    '',
    'Extend it in your own code rather than editing this file.',
  ]);
  body.block('export class GeneratedClient {', () => {
    body.line('readonly http: HttpClient;');
    for (const [groupId, group] of names.groups) {
      const tag = model.tags.find((candidate) => candidate.name === groupId);
      if (tag?.description) body.doc([tag.description]);
      body.line(`readonly ${group.property}: ${group.className};`);
    }
    body.blank();
    body.block('constructor(options: ClientOptions = {}) {', () => {
      body.line('this.http = new HttpClient({ ...options, baseUrl: options.baseUrl ?? DEFAULT_BASE_URL }, SECURITY_SCHEMES);');
      for (const group of names.groups.values()) body.line(`this.${group.property} = new ${group.className}(this.http);`);
    });
    const schemeKeys = new Set(schemes.keys());
    for (const op of rootOperations) writeOperationMethod(body, op, names.operations.get(op.key)!, ctx, schemeKeys);
  });

  return assemble(header, imports, body, []);
}

function schemeDefinition(scheme: SecurityScheme): Record<string, string> {
  switch (scheme.type) {
    case 'apiKey':
      return { type: 'apiKey', in: scheme.in, name: scheme.name };
    case 'http':
      return { type: 'http', scheme: scheme.scheme };
    default:
      return { type: scheme.type };
  }
}

function schemeUsage(scheme: SecurityScheme): string {
  switch (scheme.type) {
    case 'apiKey':
      return `API key, sent as ${scheme.in} \`${scheme.name}\`.`;
    case 'http':
      return scheme.scheme === 'basic'
        ? 'HTTP Basic credentials (or a pre-encoded token).'
        : `Token for \`Authorization: ${scheme.scheme === 'bearer' ? 'Bearer' : scheme.scheme} <token>\`.`;
    case 'oauth2':
      return 'OAuth 2 access token, sent as a Bearer token.';
    case 'openIdConnect':
      return 'OpenID Connect access token, sent as a Bearer token.';
  }
}

/** Group id → file path, e.g. `generated/api/pet-store.ts`, unique even on case-insensitive file systems. */
function assignGroupFiles(names: SdkNames): Map<string, string> {
  const used = new Set<string>();
  const files = new Map<string, string>();
  for (const [groupId, group] of names.groups) {
    const base = splitWords(group.property).map((word) => word.toLowerCase()).join('-') || 'default';
    let candidate = base;
    for (let n = 2; used.has(candidate); n++) candidate = `${base}-${n}`;
    used.add(candidate);
    files.set(groupId, `generated/api/${candidate}.ts`);
  }
  return files;
}

/** Names exported by a source file (to reserve the runtime's names and check runtime overrides). */
function exportedNames(source: string): string[] {
  const declared = [
    ...source.matchAll(/^export\s+(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(?:class|interface|type|function|const|let|var|enum)\s+([A-Za-z_$][\w$]*)/gm),
  ].map((match) => match[1]!);
  // export { A, B as C } and export type { D }
  const listed = [...source.matchAll(/^export\s+(?:type\s+)?\{([^}]*)\}/gm)].flatMap((match) =>
    match[1]!
      .split(',')
      .map((part) => part.trim().replace(/^type\s+/, '').split(/\s+as\s+/).at(-1)!.trim())
      .filter((name) => name !== ''),
  );
  return [...declared, ...listed];
}

/** Collects the imports a generated file needs, so it never imports anything unused. */
class ImportTracker {
  private readonly file: string;
  private readonly importPath: (from: string, to: string) => string;
  private readonly modules = new Map<string, Map<string, 'type' | 'value'>>();

  constructor(file: string, importPath: (from: string, to: string) => string) {
    this.file = file;
    this.importPath = importPath;
  }

  type(module: string, name: string): void {
    const names = this.namesFor(module);
    if (!names.has(name)) names.set(name, 'type');
  }

  value(module: string, name: string): void {
    this.namesFor(module).set(name, 'value');
  }

  namesFrom(module: string): string[] {
    return [...(this.modules.get(module)?.keys() ?? [])];
  }

  /** A TypeContext that imports referenced models from models.ts. */
  typeContext(names: SdkNames): TypeContext {
    return {
      ref: (key) => {
        const name = names.schemas.get(key);
        if (name === undefined) return 'unknown';
        this.type('generated/models.ts', name);
        return name;
      },
    };
  }

  render(): string[] {
    return [...this.modules]
      .filter(([module]) => module !== this.file)
      .sort(([a], [b]) => importOrder(a) - importOrder(b) || (a < b ? -1 : 1))
      .map(([module, names]) => {
        const sorted = [...names].sort(([a], [b]) => a.localeCompare(b));
        const source = stringLiteral(this.importPath(this.file, module));
        const typeOnly = sorted.every(([, kind]) => kind === 'type');
        const specifiers = sorted.map(([name, kind]) => (typeOnly || kind === 'value' ? name : `type ${name}`));
        const keyword = typeOnly ? 'import type' : 'import';
        const line = `${keyword} { ${specifiers.join(', ')} } from ${source};`;
        // Large specs import hundreds of models into one file: one per line, as a formatter would.
        return line.length <= 120 ? line : `${keyword} {\n${specifiers.map((name) => `  ${name},`).join('\n')}\n} from ${source};`;
      });
  }

  private namesFor(module: string): Map<string, 'type' | 'value'> {
    let names = this.modules.get(module);
    if (!names) this.modules.set(module, (names = new Map()));
    return names;
  }
}

function importOrder(module: string): number {
  if (module.endsWith('/runtime.ts')) return 0;
  if (module.endsWith('/models.ts')) return 2;
  return 1;
}

/** Header + imports + body. Imports are rendered last because writing the body is what discovers them. */
function assemble(header: string, imports: ImportTracker, body: CodeWriter, afterImports: readonly string[]): string {
  const writer = new CodeWriter().line(header).blank();
  for (const line of [...imports.render(), ...afterImports]) writer.line(line);
  return `${writer.toString()}\n${body.toString()}`;
}
